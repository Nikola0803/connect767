import { promises as fs } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const sourceRoot = path.join(root, "src");
const sourceCssPath = path.join(root, "node_modules", "remixicon", "fonts", "remixicon.css");
const outputDir = path.join(sourceRoot, "generated");
const outputPath = path.join(outputDir, "remixicon-subset.css");

const sourceExtensions = new Set([".js", ".jsx", ".ts", ".tsx", ".css"]);

async function collectFiles(directory) {
  const entries = await fs.readdir(directory, { withFileTypes: true });
  const files = [];
  for (const entry of entries) {
    if (entry.name === "generated") continue;
    const fullPath = path.join(directory, entry.name);
    if (entry.isDirectory()) files.push(...await collectFiles(fullPath));
    else if (sourceExtensions.has(path.extname(entry.name))) files.push(fullPath);
  }
  return files;
}

const files = await collectFiles(sourceRoot);
const icons = new Set();
for (const file of files) {
  const contents = await fs.readFile(file, "utf8");
  for (const match of contents.matchAll(/\bri-[a-z0-9-]+\b/g)) icons.add(match[0]);
}

const sourceCss = await fs.readFile(sourceCssPath, "utf8");
const iconRules = sourceCss
  .split(/\r?\n/)
  .filter((line) => {
    const match = line.match(/^\.(ri-[a-z0-9-]+):before/);
    return match && icons.has(match[1]);
  });

const utilities = sourceCss
  .split(/\r?\n/)
  .filter((line) => /^\.ri-(?:lg|xl|xxs|xs|sm|[1-9]x|fw|spin|pulse|rotate-|flip-)/.test(line));

const generated = `/* Generated by scripts/build-icon-font.mjs. Do not edit. */
@font-face {
  font-family: "remixicon";
  src: url("../../node_modules/remixicon/fonts/remixicon.woff2") format("woff2");
  font-display: swap;
}

[class^="ri-"], [class*=" ri-"] {
  font-family: "remixicon" !important;
  font-style: normal;
  -webkit-font-smoothing: antialiased;
  -moz-osx-font-smoothing: grayscale;
}

${utilities.join("\n")}
${iconRules.join("\n")}
`;

await fs.mkdir(outputDir, { recursive: true });
await fs.writeFile(outputPath, generated);
console.log(`Generated ${icons.size} Remix Icon glyph rules with WOFF2-only delivery.`);
