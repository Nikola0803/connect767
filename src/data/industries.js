/** Flat list of every industry, each tagged with its parent category. */
export const allIndustries = categoryTaxonomy.flatMap((cat) =>
  cat.industries.map((ind) => ({
    ...ind,
    categorySlug: cat.slug,
    categoryLabel: cat.label,
  }))
);

export function findIndustry(slug) {
  return allIndustries.find((i) => i.slug === slug) || null;
}

export function findCategory(slug) {
  return categoryTaxonomy.find((c) => c.slug === slug) || null;
}
